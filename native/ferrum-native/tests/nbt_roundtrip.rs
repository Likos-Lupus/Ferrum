use ferrum::nbt::limits::Limits;
use ferrum::nbt::{parser, writer};

fn vector_file() -> Vec<u8> {
    vec![
        0x0A, 0x00, 0x00, // compound, empty root name
        0x03, 0x00, 0x01, 0x78, 0x00, 0x00, 0x00, 0x05, // int x = 5
        0x08, 0x00, 0x01, 0x73, 0x00, 0x02, 0x68, 0x69, // string s = "hi"
        0x09, 0x00, 0x01, 0x6C, 0x03, 0x00, 0x00, 0x00, 0x02, // list l (int) len 2
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, // l values + root end
    ]
}

fn vector_any() -> Vec<u8> {
    vec![
        0x0A, // compound, no name
        0x03, 0x00, 0x01, 0x78, 0x00, 0x00, 0x00, 0x05, // int x = 5
        0x08, 0x00, 0x01, 0x73, 0x00, 0x02, 0x68, 0x69, // string s = "hi"
        0x09, 0x00, 0x01, 0x6C, 0x03, 0x00, 0x00, 0x00, 0x02, // list l (int) len 2
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, // l values + root end
    ]
}

fn vector_arrays() -> Vec<u8> {
    vec![
        0x0A, 0x00, 0x00, // compound, empty root name
        0x07, 0x00, 0x02, 0x62, 0x61, 0x00, 0x00, 0x00, 0x03, 0x01, 0x02, 0x03, // byte[] ba
        0x0B, 0x00, 0x02, 0x69, 0x61, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
        0x00, 0x02, // int[] ia
        0x0C, 0x00, 0x02, 0x6C, 0x61, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x07, // long[] la
        0x0A, 0x00, 0x01, 0x63, 0x01, 0x00, 0x01, 0x62, 0x7F, 0x00, // compound c { b: 0x7F }
        0x00,
    ]
}

fn vector_special_strings() -> Vec<u8> {
    vec![
        0x0A, 0x00, 0x00, // compound, empty root name
        0x08, 0x00, 0x03, 0x6E, 0x75, 0x6C, 0x00, 0x02, 0xC0, 0x80, // string "nul" = U+0000
        0x08, 0x00, 0x03, 0x73, 0x75, 0x72, 0x00, 0x06, 0xED, 0xA0, 0xBD, 0xED, 0xB8,
        0x80, // surrogate
        0x00,
    ]
}

fn round_trip(bytes: &[u8], any: bool) {
    let (arena, _) = parser::parse(bytes, Limits::default(), any).expect("parse");
    let mut arena_bytes = vec![0u8; arena.size()];
    let used = arena.serialize(&mut arena_bytes).expect("serialize");
    assert_eq!(used, arena.size());
    arena_bytes.truncate(used);

    let mut restored = vec![0u8; bytes.len() + 64];
    let written = writer::write(&arena_bytes, arena.root, !any, &mut restored).expect("write");
    restored.truncate(written);
    assert_eq!(restored, bytes);
}

#[test]
fn file_form_round_trips() {
    round_trip(&vector_file(), false);
}

#[test]
fn any_form_round_trips() {
    round_trip(&vector_any(), true);
}

#[test]
fn arrays_and_nested_compound_round_trip() {
    round_trip(&vector_arrays(), false);
}

#[test]
fn special_strings_round_trip() {
    round_trip(&vector_special_strings(), false);
}

#[test]
fn undersized_arena_reports_required() {
    let (arena, _) = parser::parse(&vector_file(), Limits::default(), false).expect("parse");
    let mut tiny = [0u8; 4];
    let required = arena.serialize(&mut tiny).expect_err("must overflow");
    assert_eq!(required, arena.size());
    assert!(required > 4);
}
